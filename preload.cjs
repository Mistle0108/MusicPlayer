const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('player', {
  load: () => ipcRenderer.invoke('load-library'),
  choose: (folder, recursive = true) => ipcRenderer.invoke('choose-music', folder, recursive),
  importDrop: files => ipcRenderer.invoke('import-dropped', files.map(file => webUtils.getPathForFile(file)).filter(Boolean)),
  save: state => ipcRenderer.invoke('save-state', state),
  mode: compact => ipcRenderer.invoke('set-mode', compact),
  expandQueue: expanded => ipcRenderer.invoke('set-compact-queue', expanded),
  onQueueExpanded: callback => ipcRenderer.on('compact-queue-changed', (_event, expanded) => callback(expanded)),
  window: action => ipcRenderer.invoke('window-action', action),
  showFile: id => ipcRenderer.invoke('show-file', id),
  removeTracks: ids => ipcRenderer.invoke('remove-tracks', ids),
  preferences: () => ipcRenderer.invoke('get-preferences'),
  savePreferences: preferences => ipcRenderer.invoke('save-preferences', preferences),
  openSettings: () => ipcRenderer.invoke('open-settings'),
  openYouTube: () => ipcRenderer.invoke('open-youtube'),
  youtubeState: () => ipcRenderer.invoke('youtube-state'),
  youtubeOptions: options => ipcRenderer.invoke('youtube-options', options),
  youtubeFolder: folder => ipcRenderer.invoke('youtube-folder', folder),
  youtubeOpenFolder: folder => ipcRenderer.invoke('youtube-open-folder', folder),
  youtubeExtract: url => ipcRenderer.invoke('youtube-extract', url),
  youtubeSave: folder => ipcRenderer.invoke('youtube-save', folder),
  onYouTubeProgress: callback => ipcRenderer.on('youtube-progress', (_event, message) => callback(message)),
  onLibraryImported: callback => ipcRenderer.on('library-imported', (_event, tracks) => callback(tracks)),
  onPreferences: callback => ipcRenderer.on('preferences-changed', (_event, value) => callback(value)),
  onClose: callback => ipcRenderer.on('save-before-close', callback),
  closeReady: () => ipcRenderer.invoke('close-ready'),
  onMode: callback => ipcRenderer.on('mode-changed', (_event, value) => callback(value))
});
